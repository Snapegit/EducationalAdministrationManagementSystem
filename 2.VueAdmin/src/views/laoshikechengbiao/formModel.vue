							<el-input class="list_inp" v-model.number="form.renshu" placeholder="人数"
								 type="text" 								:readonly="!isAdd||disabledForm.renshu?true:false" />
						</el-form-item>
					</el-col>

					<el-col :span="12">
						<el-form-item label="上课时间" prop="shangkeshijian">
							<el-input class="list_inp" v-model="form.shangkeshijian" placeholder="上课时间"
								 type="text" 								:readonly="!isAdd||disabledForm.shangkeshijian?true:false" />
						</el-form-item>
					</el-col>

					<el-col :span="12">
						<el-form-item label="教师工号" prop="jiaoshigonghao">
							<el-select
								class="list_sel"
								:disabled="!isAdd||disabledForm.jiaoshigonghao?true:false"
